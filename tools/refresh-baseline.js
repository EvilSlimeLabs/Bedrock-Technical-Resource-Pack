'use strict';

/**
 * `node tools/refresh-baseline.js` — regenerate `tools/vanilla-baseline.json`
 * from Mojang's published vanilla resource pack.
 *
 * A client entity file in a resource pack *replaces* the vanilla one; it does
 * not merge with it. Every short name the pack's copy fails to carry over is a
 * name vanilla's own animation and render controllers will still ask for and
 * not find. The baseline records what vanilla declares so `npm run audit` can
 * say which ones have been dropped.
 *
 * Run this after Mojang ships a version that adds animations to an entity this
 * pack overrides, and act on whatever the audit then reports. It is a manual
 * step on purpose: it needs the network, so it is not part of `npm run
 * release`.
 */

const fs = require('node:fs');
const path = require('node:path');
const { parseJsonc } = require('./lib/jsonc.js');
const { loadPack } = require('./lib/pack.js');
const { ROOT } = require('./lib/cli.js');

const SAMPLES = 'https://raw.githubusercontent.com/Mojang/bedrock-samples/main';

/** Short-name maps that a replaced client entity has to carry over. */
const CATEGORIES = ['animations', 'textures', 'materials', 'geometry'];

/**
 * @param {string} url
 * @returns {Promise<string>}
 */
async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
  return response.text();
}

async function main() {
  const index = loadPack(ROOT);
  const entities = index.entities.map(({ packPath, description }) => ({
    identifier: description.identifier,
    // The vanilla file has the same name as the pack's copy of it.
    url: `${SAMPLES}/resource_pack/${packPath}`,
  }));

  const version = JSON.parse(await fetchText(`${SAMPLES}/version.json`)).latest.version;
  const out = {
    _comment: [
      'Generated by `node tools/refresh-baseline.js` from Mojang/bedrock-samples.',
      'For each vanilla client entity this pack replaces, the short names vanilla',
      'declares. A replaced entity file does not merge with vanilla, so a short',
      'name missing here is one vanilla controllers will ask for and not find.',
      'Do not edit by hand; re-run the script instead.',
    ],
    generated_from: version,
    entities: {},
  };

  for (const { identifier, url } of entities) {
    const doc = parseJsonc(await fetchText(url), url);
    const description = doc['minecraft:client_entity']?.description ?? {};
    const record = {};
    for (const category of CATEGORIES) {
      const keys = Object.keys(description[category] ?? {});
      if (keys.length > 0) record[category] = keys;
    }
    out.entities[identifier] = record;
    console.log(`refresh-baseline: ${identifier} — ${CATEGORIES.map((c) => `${(record[c] ?? []).length} ${c}`).join(', ')}`);
  }

  const file = path.join(ROOT, 'tools', 'vanilla-baseline.json');
  fs.writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
  console.log(`refresh-baseline: wrote tools/vanilla-baseline.json from vanilla ${version}`);
}

main().catch((err) => {
  console.error(`refresh-baseline: ${err.message}`);
  process.exitCode = 1;
});
